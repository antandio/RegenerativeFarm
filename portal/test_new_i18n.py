"""Stage6 TDD RED: full HU/EN coverage of all new UI (locations, properties,
equipment, crops/cycles, staff/members, plans, weather, chat) in both locales.

Asserts English headings with no Hungarian leakage under /en/, Hungarian
headings/labels with no English fallback under /hu/, translated form labels,
role labels and error messages (not just single words).
"""
from django.test import TestCase
from django.contrib.auth import get_user_model
from portal.models import Farm, Membership
from portal.tests import make_user

U = get_user_model()


def switch(client, lang, next_url="/attekintes/"):
    return client.post("/i18n/setlang/", {"language": lang, "next": next_url})


def msgs(response):
    return [m.message for m in response.context["messages"]]


class NewUiEnglishTests(TestCase):
    def setUp(self):
        self.owner = make_user("owner6@pelda.hu")
        self.farm = Farm.objects.create(owner=self.owner, name="Stage6 farm")
        self.client.force_login(self.owner)
        switch(self.client, "en")

    def test_en_crud_list_headings_no_hungarian(self):
        cases = [
            ("/locations/", "Locations"),
            ("/properties/", "Plots"),
            ("/equipment/", "Machines"),
            ("/cycles/", "Crop cycles"),
        ]
        for url, en in cases:
            r = self.client.get(url)
            self.assertEqual(r.status_code, 200, url)
            b = r.content.decode()
            self.assertIn('<html lang="en">', b, url)
            self.assertIn(en, b, url)
            for hu in ("Helyszínek", "Területek", "Gépek", "Vetésforgók"):
                self.assertNotIn(hu, b, f"{hu} leaked on {url}")

    def test_en_crud_form_labels_no_hungarian(self):
        cases = [
            ("/locations/new/", "Location name"),
            ("/properties/new/", "Plot name"),
            ("/equipment/new/", "Machine name"),
            ("/cycles/new/", "Crop name"),
        ]
        for url, en in cases:
            r = self.client.get(url)
            self.assertEqual(r.status_code, 200, url)
            b = r.content.decode()
            self.assertIn(en, b, url)
            for hu in ("Helyszín neve", "Terület neve", "Gép neve", "Növény neve"):
                self.assertNotIn(hu, b, f"{hu} leaked on {url}")

    def test_en_staff_plans_weather_chat_no_hungarian(self):
        cases = [
            ("/tagok/", "Members"),
            ("/terv/", "Work plan"),
            ("/weather/", "Weather"),
            ("/chat/", "Chat"),
        ]
        for url, en in cases:
            r = self.client.get(url)
            self.assertEqual(r.status_code, 200, url)
            b = r.content.decode()
            self.assertIn('<html lang="en">', b, url)
            self.assertIn(en, b, url)
            for hu in ("Tagok", "Munkaterv", "Időjárás", "Csevegés"):
                self.assertNotIn(hu, b, f"{hu} leaked on {url}")

    def test_en_role_error_and_invite_error_english(self):
        w = make_user("w6@pelda.hu")
        mem = Membership.objects.create(farm=self.farm, user=w, role="worker")
        r = self.client.post(f"/tagok/{mem.id}/szerep/", {"role": "nonsense"}, follow=True)
        self.assertIn("Invalid role.", msgs(r))
        r = self.client.post("/tagok/meghivas/", {"email": "not-an-email", "role": "worker"})
        self.assertEqual(r.status_code, 400)
        self.assertIn("Invalid invitation data.", msgs(r))


